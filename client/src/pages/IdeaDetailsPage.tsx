import { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";
import AnalysisCard from "../components/AnalysisCard";
import Header from "../components/Header";
import LoadingSpinner from "../components/LoadingSpinner";
import Sidebar from "../components/Sidebar";
import { getIdeaById } from "../services/ideaService";
import type { Idea } from "../types/idea";

function IdeaDetailsPage() {
  const { id } = useParams();

  const [idea, setIdea] = useState<Idea | null>(null);
  const [error, setError] = useState("");
  const [isLoading, setIsLoading] = useState(true);

  useEffect(() => {
    async function loadIdea() {
      if (!id) {
        setError("Idea id is missing.");
        setIsLoading(false);
        return;
      }

      try {
        const data = await getIdeaById(id);
        setIdea(data);
      } catch (err) {
        setError(err instanceof Error ? err.message : "Failed to load idea.");
      } finally {
        setIsLoading(false);
      }
    }

    loadIdea();
  }, [id]);

  return (
    <div className="app-shell">
      <Sidebar />

      <main className="main-content">
        <Header
          eyebrow="Saved report"
          title="Idea details"
          description="Review the full NABC analysis generated by your AI assistant."
        />

        {isLoading && <LoadingSpinner text="Loading saved analysis..." />}
        {error && <p className="error-message">{error}</p>}

        {!isLoading && !error && !idea && (
          <div className="empty-state">
            <h3>Idea not found</h3>

            <Link className="primary-link" to="/ideas">
              Back to history
            </Link>
          </div>
        )}

        {idea && (
          <>
            <section className="idea-detail-card">
              <div>
                <p className="eyebrow">Original idea</p>
                <h2>{idea.idea_text}</h2>
              </div>

              {idea.created_at && (
                <span>{new Date(idea.created_at).toLocaleString()}</span>
              )}
            </section>

            <section className="result-grid details-grid">
              <AnalysisCard index="N" title="Need" text={idea.need} />

              <AnalysisCard index="A" title="Approach" text={idea.approach} />

              <AnalysisCard index="B" title="Benefit" text={idea.benefit} />

              <AnalysisCard
                index="C"
                title="Competition"
                text={idea.competition}
              />
            </section>
          </>
        )}
      </main>
    </div>
  );
}

export default IdeaDetailsPage;